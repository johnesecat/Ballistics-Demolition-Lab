export function getAmmoById(id: string): AmmoDefinition | undefined {
  return AMMO_CATALOGUE.find(a => a.id === id);
}

export function getAmmoByCategory(category: Exclude<AmmoCategory, 'all'>): AmmoDefinition[] {
  return AMMO_CATALOGUE.filter(a => a.category === category);
}

export function getAmmoByMaterialFilter(filter: MaterialFilter): AmmoDefinition[] {
  return AMMO_CATALOGUE.filter(a => {
    const mod = a.stats.materialModifiers[filter];
    return mod !== undefined && mod > 1.0;
  });
}

export function getAllAmmo(): AmmoDefinition[] {
  return [...AMMO_CATALOGUE];
}

export function getUnlockedAmmo(): AmmoDefinition[] {
  return AMMO_CATALOGUE.filter(a => a.unlocked);
}

export function getSoftAmmo(): AmmoDefinition[] {
  return AMMO_CATALOGUE.filter(a => a.subcategory === 'soft');
}